-- 10 - Criação da tabela de versões publicadas do aplicativo

CREATE TABLE TB_VITALIA_APP_VERSION (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    VERSION VARCHAR2(30) NOT NULL,
    COMMIT_HASH VARCHAR2(64) NOT NULL,
    BRANCH VARCHAR2(100) NOT NULL,
    PUBLISHED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_VITALIA_APP_VERSION
        PRIMARY KEY (ID),

    CONSTRAINT UK_VITALIA_APP_VERSION_VERSION
        UNIQUE (VERSION)
);